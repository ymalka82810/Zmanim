/** נוסח כשורות לתצוגה: { note } להוראה, { say } לטקסט לאמירה */
export function textLines(text) {
  return String(text || '')
    .split('\n')
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => (s.startsWith('*') ? { note: s.slice(1).trim() } : { say: s }));
}
