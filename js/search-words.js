const PREFIXES = 'ובלהמשכ';

/** טקסט להשוואה */
export function normalize(text) {
  return String(text ?? '')
    .toLowerCase()
    .replace(/[֑-ׇ]/g, '')
    .replace(/[׳״'"`]/g, '')
    .replace(/[ךםןףץ]/g, (c) => ({ ך: 'כ', ם: 'מ', ן: 'נ', ף: 'פ', ץ: 'צ' })[c] ?? c)
    .replace(/([וי])\1+/g, '$1')
    .replace(/[\s\-–—_.,:;!?()/\\·]+/g, ' ')
    .trim();
}

const GROUPS = SYNONYMS.map((g) => g.map(normalize));
/** צירופים של כמה מילים, מהארוך לקצר, כדי שחיפוש "יום השנה" ייחשב מונח אחד */
const PHRASES = [...new Set(GROUPS.flat().filter((w) => w.includes(' ')))].sort((a, b) => b.length - a.length);

/** הצורות של מונח אחד: הוא עצמו, בלי אות שימוש בתחילתו, בלי ריבוי בסופו, ומילים נרדפות לכל אחת מאלה.
 * צורה שהורידו ממנה אות שימוש מתחילה ברווח: היא מתאימה רק בתחילת מילה ("ברית" לא ימצא "שחרית") */
function forms(term) {
  const base = new Set([term]);
  for (let i = 1; i <= 2 && term.length - i >= 3 && PREFIXES.includes(term[i - 1]); i++) base.add(' ' + term.slice(i));
  for (const w of [...base]) {
    if (w.trim().length >= 5 && /(ימ|ות)$/.test(w)) base.add(w.slice(0, -2));
  }
  const bare = new Set([...base].map((w) => w.trim()));
  const all = new Set(base);
  for (const g of GROUPS) {
    if (g.some((s) => bare.has(s))) g.forEach((s) => all.add(s));
  }
  return [...all];
}

/** החיפוש כרשימת מונחים, ולכל מונח – כל הצורות שמתאימות לו. [] – אין מה לחפש (פחות משתי אותיות) */
export function parseQuery(q) {
  let phrase = normalize(String(q ?? '').slice(0, 80));
  if (phrase.length < 2) return [];
  const terms = [];
  for (const p of PHRASES) {
    const re = new RegExp('(^| )' + p + '(?= |$)', 'g');
    if (re.test(phrase)) {
      terms.push(p);
      phrase = phrase.replace(re, ' ');
    }
  }
  terms.push(...phrase.split(' ').filter(Boolean));
  return terms.map(forms);
}

/** ציון התאמה של רשומה: 0 – לא מתאימה. כל מונח חייב להופיע (באחת מצורותיו) בכותרת או בשאר הטקסט;
 * התאמה בכותרת, ובמיוחד בתחילת מילה בה, מקבלת ציון גבוה יותר. מונח בצורה המקורית שלו – מעט יותר ממילה נרדפת */
export function score(title, rest, query) {
  const t = ' ' + normalize(title);
  const all = t + ' ' + normalize(rest);
  let s = 0;
  for (const alts of query) {
    let best = 0;
    alts.forEach((a, i) => {
      const exact = i === 0 ? 0.5 : 0;
      const v = t.includes(a[0] === ' ' ? a : ' ' + a) ? 3 : t.includes(a) ? 2 : all.includes(a) ? 1 : 0;
      if (v) best = Math.max(best, v + exact);
    });
    if (!best) return 0;
    s += best;
  }
  return s;
}
